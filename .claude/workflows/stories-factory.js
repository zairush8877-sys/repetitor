export const meta = {
  name: 'stories-factory',
  description: 'Пересборка банка сторис: трендовые спорные вопросы вместо хрестоматии',
  whenToUse: 'Когда банк сторис надо заменить на вопросы, в которых сомневается грамотный взрослый',
  phases: [
    { title: 'Черновик', detail: 'копирайтер собирает банк из фактуры трендов' },
    { title: 'Корректор', detail: 'каждый факт по словарю, тест на примитивность' },
    { title: 'Редактор', detail: 'финальная сборка' },
  ],
}

const input = typeof args === 'string' ? JSON.parse(args) : args
if (!input || !input.research) throw new Error('stories-factory: в args нет research')

const COUNT = input.count || 13
const RESEARCH = input.research

const TONE = `Правила (нарушение = переделка):
- Запрещённые клише: «А вы знали?», «Сохраните, чтобы не потерять», «Спойлер:», «Друзья!».
- Тест на примитивность — главный: если пара разбирается в школьном учебнике
  (норма автора — не чаще одной такой сторис в неделю, с пометкой school: true)
  («эффектный/эффективный», «представить/предоставить», «одеть/надеть»), сторис
  бракуется. Планка: ГРАМОТНЫЙ ВЗРОСЛЫЙ должен засомневаться или удивиться.
- Аудитория: родители выпускников и взрослые, которым важна грамотность.
- Личные запреты автора: «одеть/надеть» не использовать; спорные пары с двумя
  допустимыми нормами (риэлтор/риелтор) не брать в формат «как правильно» —
  но МОЖНО в формат «обе формы верны, и вот почему», если это сам факт.`

const SCHEMA = {
  type: 'object',
  properties: {
    stories: {
      type: 'array', minItems: COUNT, maxItems: COUNT,
      items: {
        type: 'object',
        properties: {
          id: { type: 'string', description: 'временный, s1..s13' },
          type: { type: 'string', enum: ['vopros', 'fakt'] },
          q: { type: 'string', description: 'vopros: вопрос первого кадра, ≤24 знаков' },
          a: { type: 'string', description: 'vopros: вариант A, ≤16 знаков' },
          b: { type: 'string', description: 'vopros: вариант B, ≤16 знаков' },
          right: { type: 'string', description: 'vopros: a или b' },
          top: { type: 'string', description: 'fakt: надпись сверху, ≤22 знаков' },
          big: { type: 'string', description: 'fakt: крупная надпись, ≤22 знаков, \\n для переноса' },
          why: { type: 'string', description: 'второй кадр: ровно две строки через \\n, каждая ≤65 знаков' },
          source: { type: 'string', description: 'словарь/статья, которыми факт подтверждается' },
          hook: { type: 'string', description: 'почему грамотный взрослый засомневается — одна фраза' },
        },
        required: ['id', 'type', 'why', 'source', 'hook'],
      },
    },
  },
  required: ['stories'],
}

phase('Черновик')
const draft = await agent(
  `Ты копирайтер аккаунта репетитора русского языка @mairova_a_a.
Собери банк из ${COUNT} сторис-викторин НА ОСНОВЕ ТРЕНДОВ — вопросы, которые
люди реально гуглят и о которых спорят, а не хрестоматия.

ФАКТУРА (бери только подтверждённое источником; «НЕ ПОДТВЕРЖДЕНО» не брать):
${RESEARCH}

${TONE}

Структура: два кадра — интрига и ответ. Типы:
- vopros: q — вопрос, a/b — варианты, right — верный, why — объяснение;
- fakt: top — подводка, big — сенсация («это слово в словаре»), why — объяснение.

Пропорция примерно 9 vopros / 4 fakt. Лимиты длины соблюдай строго — это
вертикальный экран. В hook напиши, чем вопрос цепляет взрослого: это фильтр
против примитивности, редактор выбросит сторис со слабым hook.`,
  { label: 'копирайтер', phase: 'Черновик', schema: SCHEMA })

phase('Корректор')
const verdict = await agent(
  `Ты корректор аккаунта учителя русского языка: одна фактическая ошибка стоит
репутации, а один примитивный вопрос — интереса аудитории.

Банк: ${JSON.stringify(draft.stories)}

По каждой сторис ответь:
- верен ли факт и подтверждает ли его указанный источник (проверь точную
  словарную форму: кешбэк/кэшбек и подобные легко перепутать);
- для vopros: действительно ли верен вариант right и нет ли у второго варианта
  словарной пометы «допустимо», которая делает вопрос спорным;
- тест на примитивность: разбирается ли пара в школьном учебнике; норма —
  не чаще одной такой в неделю, помечать school: true; сверх нормы —
  вердикт «примитивно», сторис заменяется;
- лимиты: q ≤ 24, a/b ≤ 16, big ≤ 22, каждая строка why ≤ 65.
Для проблемных предложи замену из фактуры.`,
  { label: 'корректор', phase: 'Корректор', schema: {
    type: 'object',
    properties: {
      verdicts: {
        type: 'array',
        items: {
          type: 'object',
          properties: {
            id: { type: 'string' },
            ok: { type: 'boolean' },
            comment: { type: 'string' },
            action: { type: 'string', enum: ['оставить', 'исправить', 'заменить'] },
          },
          required: ['id', 'ok', 'comment', 'action'],
        },
      },
      summary: { type: 'string' },
    },
    required: ['verdicts', 'summary'],
  } })

phase('Редактор')
const final = await agent(
  `Ты выпускающий редактор. Собери финальный банк сторис.
Черновик: ${JSON.stringify(draft.stories)}
Вердикт корректора: ${JSON.stringify(verdict)}
${TONE}
Всё помеченное «заменить» замени материалом из фактуры (подтверждённым!),
«исправить» — исправь. Ровно ${COUNT} сторис, id s1..s${COUNT}, лимиты строго.`,
  { label: 'редактор', phase: 'Редактор', schema: SCHEMA })

log(`Готово сторис: ${final.stories.length}; корректор: ${verdict.summary.slice(0, 120)}`)
return { stories: final.stories, review: verdict.summary }
